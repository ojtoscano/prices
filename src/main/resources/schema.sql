CREATE TABLE BRAND (
    BRAND_ID        INT PRIMARY KEY,
    NAME            VARCHAR(100) NOT NULL
);

CREATE TABLE PRODUCT (
    PRODUCT_ID      INT PRIMARY KEY,
    NAME            VARCHAR(255) NOT NULL
);

CREATE TABLE TARIFF (
    TARIFF_ID       INT PRIMARY KEY,
    NAME            VARCHAR(255) NOT NULL
);

CREATE TABLE PRICE (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BRAND_ID        INT NOT NULL REFERENCES BRAND(BRAND_ID),
    PRODUCT_ID      INT NOT NULL REFERENCES PRODUCT(PRODUCT_ID),
    TARIFF_ID       INT NOT NULL REFERENCES TARIFF(TARIFF_ID),
    START_DATE      TIMESTAMP(0) NOT NULL,
    END_DATE        TIMESTAMP(0) NOT NULL,  
    PRIORITY        INT NOT NULL,
    AMOUNT          DECIMAL(10, 2) NOT NULL,
    CURRENCY_CODE   CHAR(3) NOT NULL,
    CONSTRAINT CHK_PRICE_DATE CHECK (END_DATE >= START_DATE),
    CONSTRAINT CHK_PRICE_AMOUNT CHECK (AMOUNT >= 0),
    CONSTRAINT UQ_PRICE UNIQUE (BRAND_ID, PRODUCT_ID, TARIFF_ID, START_DATE, END_DATE)
);

CREATE INDEX IDX_PRICE_LOOKUP ON PRICE (BRAND_ID, PRODUCT_ID, TARIFF_ID, START_DATE, END_DATE, PRIORITY DESC);

